// ─────────────────────────────────────────────────────────────
//  Generates iOS home-screen splash screens (apple-touch-startup-image).
//
//  Without these, an iPhone shows a blank white screen while the
//  installed app cold-boots. With them, the launch feels native.
//
//  Run:  node scripts/make-splash.mjs
//  Emits: public/splash/<device>.png  +  lib/splash-screens.ts
// ─────────────────────────────────────────────────────────────

import sharp from 'sharp'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = path.join(ROOT, 'public', 'splash')
const TS_OUT = path.join(ROOT, 'lib', 'splash-screens.ts')

// Matches --background (dark) and manifest.background_color.
const BACKGROUND = '#0a0a14'
// Matches the primary accent hue used by the dark theme.
const GLOW = '#7c5cff'

/**
 * Portrait logical sizes for every iPhone that can run iOS 15+.
 * `dpr` is the device pixel ratio used by the media query.
 */
const DEVICES = [
  { slug: 'iphone-16-pro-max', width: 440, height: 956, dpr: 3 },
  { slug: 'iphone-16-pro', width: 402, height: 874, dpr: 3 },
  { slug: 'iphone-15-pro-max', width: 430, height: 932, dpr: 3 },
  { slug: 'iphone-16-plus', width: 430, height: 932, dpr: 3 },
  { slug: 'iphone-14-plus', width: 428, height: 926, dpr: 3 },
  { slug: 'iphone-16', width: 393, height: 852, dpr: 3 },
  { slug: 'iphone-15', width: 393, height: 852, dpr: 3 },
  { slug: 'iphone-14-pro', width: 393, height: 852, dpr: 3 },
  { slug: 'iphone-16e', width: 390, height: 844, dpr: 3 },
  { slug: 'iphone-14', width: 390, height: 844, dpr: 3 },
  { slug: 'iphone-13', width: 390, height: 844, dpr: 3 },
  { slug: 'iphone-13-mini', width: 375, height: 812, dpr: 3 },
  { slug: 'iphone-11-pro-max', width: 414, height: 896, dpr: 3 },
  { slug: 'iphone-11', width: 414, height: 896, dpr: 2 },
  { slug: 'iphone-11-pro', width: 375, height: 812, dpr: 3 },
  { slug: 'iphone-8-plus', width: 414, height: 736, dpr: 3 },
  { slug: 'iphone-se', width: 375, height: 667, dpr: 2 },
]

/** Pull the two glyph path `d` values straight out of the app icon. */
async function readGlyphPaths() {
  const svg = await readFile(path.join(ROOT, 'public', 'icon.svg'), 'utf8')
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (paths.length < 2) throw new Error('Could not find glyph paths in public/icon.svg')
  return paths
}

function buildSvg(paths, pixelWidth, pixelHeight) {
  // The glyph lives in a 180×180 box; scale it to ~30% of the short edge.
  const box = Math.round(Math.min(pixelWidth, pixelHeight) * 0.26)
  const scale = box / 180
  const offsetX = (pixelWidth - box) / 2
  const offsetY = (pixelHeight - box) / 2

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${pixelWidth}" height="${pixelHeight}" viewBox="0 0 ${pixelWidth} ${pixelHeight}">
  <defs>
    <radialGradient id="glow" cx="50%" cy="42%" r="55%">
      <stop offset="0%" stop-color="${GLOW}" stop-opacity="0.22"/>
      <stop offset="55%" stop-color="${GLOW}" stop-opacity="0.07"/>
      <stop offset="100%" stop-color="${GLOW}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="${pixelWidth}" height="${pixelHeight}" fill="${BACKGROUND}"/>
  <rect width="${pixelWidth}" height="${pixelHeight}" fill="url(#glow)"/>
  <g transform="translate(${offsetX} ${offsetY}) scale(${scale})" fill="#ffffff">
    ${paths.map((d) => `<path d="${d}"/>`).join('\n    ')}
  </g>
</svg>`
}

function mediaQuery({ width, height, dpr }) {
  return `(device-width: ${width}px) and (device-height: ${height}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)`
}

async function main() {
  const paths = await readGlyphPaths()
  await mkdir(OUT_DIR, { recursive: true })

  for (const device of DEVICES) {
    const pixelWidth = device.width * device.dpr
    const pixelHeight = device.height * device.dpr
    const svg = buildSvg(paths, pixelWidth, pixelHeight)
    const target = path.join(OUT_DIR, `${device.slug}.png`)

    await sharp(Buffer.from(svg))
      .png({ compressionLevel: 9, palette: false })
      .toFile(target)

    console.log(`  ${device.slug.padEnd(20)} ${pixelWidth}×${pixelHeight}`)
  }

  const entries = DEVICES.map((device) => ({
    href: `/splash/${device.slug}.png`,
    media: mediaQuery(device),
  }))

  const ts = `// AUTO-GENERATED by scripts/make-splash.mjs — do not edit by hand.
// Regenerate with: node scripts/make-splash.mjs

export interface SplashScreen {
  href: string
  media: string
}

export const SPLASH_SCREENS: readonly SplashScreen[] = [
${entries.map((e) => `  { href: '${e.href}', media: '${e.media}' },`).join('\n')}
]
`
  await writeFile(TS_OUT, ts, 'utf8')
  console.log(`\nGenerated ${DEVICES.length} splash screens + lib/splash-screens.ts`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
